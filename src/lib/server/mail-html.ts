/* ============================================================
 * 邮件 HTML 模板转义（单一实现）
 *
 * cron/tick（提醒邮件）与 cron/weekly-digest（周报邮件）的收件人字段都来自
 * 用户任意输入（r.title/r.prompt、k.title/k.topic 等，限长但内容不限字符），
 * 未转义就拼进 HTML 会让提醒/周报邮件变成可投递任意 HTML 的通道
 * （伪造按钮/链接/追踪像素的钓鱼样式）。
 *
 * 此前两个路由各持一份逐字相同的本地 escapeHtml（admin/overview 点名的
 * 「收口到单一实现，此前本文件复制过一份——漂移即事故隐患」反模式）：
 * 两份拷贝一旦只有一份修了转义缺口，同一条用户输入在两条 cron 链路上
 * 获得不同等级的注入防护。现在收口到这里，两处 import 同一实现。
 *
 * 字符集固定为 & < > "（按序替换，& 必须最先）：与两份旧实现逐字一致，
 * 存量邮件渲染不变；属性上下文若需要单引号转义，改这里即可两条链路同时生效。
 * ============================================================ */
export function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
