import { chromium } from 'playwright-core';
import fs from 'fs';
const cookie = fs.readFileSync('smoke.txt','utf8').match(/mentora_session\s+(\S+)/)[1];
const EXE='C:/Users/haozhe/AppData/Local/ms-playwright/chromium-1243/chrome-win64/chrome.exe';
const b = await chromium.launch({ executablePath: EXE, headless: true });
const ctx = await b.newContext({ viewport:{width:1440,height:900} });
const p = await ctx.newPage();
const errs=[]; p.on('pageerror',e=>errs.push(String(e).slice(0,150)));
await ctx.addCookies([{name:'mentora_session',value:cookie,url:'http://localhost:3000'}]);
await p.goto('http://localhost:3000/life',{waitUntil:'networkidle',timeout:30000}).catch(()=>{});
await p.waitForTimeout(2500);
const life = await p.textContent('body');
console.log('LIFE 页:', life.includes('学习人生') && life.includes('足迹') && life.includes('里程碑'));
const period = await p.evaluate(()=>document.documentElement.getAttribute('data-period'));
console.log('时段主题 data-period:', period);
await p.goto('http://localhost:3000/learn',{waitUntil:'networkidle'}).catch(()=>{});
await p.waitForTimeout(2000);
const learn = await p.textContent('body');
console.log('LEARN 方向卡:', learn.includes('不知道学什么'));
console.log('侧栏学习人生:', learn.includes('学习人生'));
console.log('ERRORS:', JSON.stringify(errs.slice(0,4)));
await b.close();
